export function ponerIcono(el, nombre, tam) { el.innerHTML = icono(nombre, tam); return el; }
// Rellena todos los <span data-ic="nombre"> que haya dentro de la raíz.
export function pintarIconos(raiz = document) {
  raiz.querySelectorAll('[data-ic]').forEach((el) => { if (!el.firstChild) el.innerHTML = icono(el.dataset.ic, +el.dataset.tam || 24); });
}
